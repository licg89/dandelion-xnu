#!/usr/bin/env python3
"""Extract the Dandelion 8x16 console font from a patched XNU tree.

The framebuffer console in osfmk/kern/printf.c draws each character from
dandelion_font8x16[][]; bootshim/font.h carries the same table.  Keeping a
copy here lets tools/qemu/qemu_run.py turn a framebuffer dump back into text
without OCR, which is the only way to read the kernel's output under QEMU
(the trace ring at 0x5fc00000 is ordinary RAM and gets reused after boot).

usage: gen_font.py <xnu-tree>/osfmk/kern/printf.c [output.py]
"""
import os
import re
import sys

def main():
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    source, output = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2
                                   else os.path.join(os.path.dirname(__file__),
                                                     "font8x16.py"))
    text = open(source, encoding="utf-8", errors="replace").read()
    if "dandelion_font8x16[95][16]" not in text:
        print("gen_font: %s has no dandelion_font8x16 table" % source,
              file=sys.stderr)
        return 1
    block = text.split("dandelion_font8x16[95][16] = {", 1)[1].split("};", 1)[0]
    rows = re.findall(r"\{([^}]*)\}", block)
    font = []
    for row in rows:
        values = [int(v, 16) for v in row.replace("\n", " ").split(",") if v.strip()]
        assert len(values) == 16, values
        font.append(bytes(values))
    assert len(font) == 95, len(font)

    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write('"""8x16 console font used by the Dandelion framebuffer console.\n\n')
        handle.write("Generated by tools/qemu/gen_font.py from the\n")
        handle.write("dandelion_font8x16 table in osfmk/kern/printf.c (the same glyphs\n")
        handle.write("bootshim/font.h carries).  Index 0 is character 0x20 (space).\n")
        handle.write('"""\n\nFONT = (\n')
        for glyph in font:
            handle.write("    %r,\n" % glyph)
        handle.write(")\n\nFIRST_CHAR = 0x20\n")
    print("wrote %s (%d glyphs)" % (output, len(font)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
