#!/bin/bash
# Build the QEMU boot shim (tools/qemu/shim) -- a standalone AArch64 program
# that QEMU's -kernel loads at 0x40080000 and that hands mach_kernel the boot
# environment DarwinBoot gives it on the phone.
#
# Needs an AArch64 cross compiler and nothing else:
#   aarch64-linux-gnu-gcc   (apt install gcc-aarch64-linux-gnu)
#   clang + ld.lld          (CC=clang, --target=aarch64-none-elf)
#
# Usage: tools/qemu/build.sh [--clean]
set -euo pipefail
cd "$(dirname "$0")/shim"

if [ "${1:-}" = "--clean" ]; then
	rm -rf out
	echo "cleaned"
	exit 0
fi

if [ -z "${CC:-}" ]; then
	if command -v aarch64-linux-gnu-gcc >/dev/null 2>&1; then
		CC=aarch64-linux-gnu-gcc
	elif command -v clang >/dev/null 2>&1; then
		CC=clang
	else
		echo "build.sh: no aarch64 cross compiler found" >&2
		exit 1
	fi
fi

case "$CC" in
*clang*)
	TARGET="--target=aarch64-none-elf"
	LINKER="-fuse-ld=lld"
	OBJDUMP=llvm-objdump
	;;
*)
	TARGET=""
	LINKER=""
	OBJDUMP=aarch64-linux-gnu-objdump
	;;
esac

CFLAGS="-O2 -ffreestanding -nostdlib -fno-pic -mgeneral-regs-only
        -mstrict-align -fno-stack-protector -fno-builtin -mcpu=cortex-a53
        -fno-asynchronous-unwind-tables -Wall -Wextra -Wno-unused-function"

# The ramdisk the shim advertises in /chosen/memory-map, so that mockfs can
# mount and load_init_program() can exec -- the phone's path.  16 KiB arm64
# Mach-O, from tools/mk_init_macho.py.  RAMDISK= (empty) builds without one.
REPO=$(cd ../../.. && pwd)
RAMDISK=${RAMDISK-$REPO/Resources/UniXNU/kernel.macho.rd}
RAMDISK_SIZE=0
if [ -n "$RAMDISK" ] && [ -f "$RAMDISK" ]; then
	RAMDISK_SIZE=$(stat -c %s "$RAMDISK")
fi
echo "ramdisk: ${RAMDISK:-(none)} (${RAMDISK_SIZE} bytes)"

mkdir -p out
echo "=== building the QEMU shim with $CC ==="

# ADT_BLOB=path builds the shim around a *real* device tree instead of the one
# adt_qemu.c synthesises.  QEMU's own tree describes virtio and a GICv3 at
# 0x08000000, which is what makes ticks work, but it is not the phone's tree: the
# IOKit registry it produces is a different shape, so a crash there may be an
# artifact of the synthetic tree rather than a port bug.  Building with
# ADT_BLOB=$REPO/Resources/UniXNU/kernel.macho.adt (the phone's own 6044-byte blob)
# removes that variable - at the price of the GIC living at 0x0c000000, where QEMU
# has nothing, so ticks stop and -dl_qemu must gate the GIC bring-up again.
ADT_OBJ=""
ADT_DEF=""
if [ -n "${ADT_BLOB:-}" ] && [ -f "${ADT_BLOB}" ]; then
	cp "$ADT_BLOB" out/adt_blob.bin
	aarch64-linux-gnu-objcopy -I binary -O elf64-littleaarch64 -B aarch64 \
		--rename-section .data=.rodata,alloc,load,readonly,data,contents \
		out/adt_blob.bin out/adt_blob.o
	ADT_OBJ=out/adt_blob.o
	ADT_DEF="-DHAVE_ADT_BLOB"
	echo "adt: using the blob $ADT_BLOB ($(stat -c %s "$ADT_BLOB") bytes)"
else
	echo "adt: generated by adt_qemu.c"
fi

$CC $TARGET $CFLAGS -c start.S   -o out/start.o
$CC $TARGET $CFLAGS $ADT_DEF -DRAMDISK_SIZE=${RAMDISK_SIZE}UL -c shim.c -o out/shim.o
$CC $TARGET $CFLAGS -c adt_qemu.c -o out/adt_qemu.o
$CC $TARGET $CFLAGS $LINKER -static -T shim.ld -Wl,--build-id=none \
	-Wl,-e,_start out/start.o out/shim.o out/adt_qemu.o $ADT_OBJ -o out/shim.elf

echo ""
$OBJDUMP -h out/shim.elf | sed -n '1,20p'
echo ""
echo "shim: $(stat -c %s out/shim.elf) bytes"
